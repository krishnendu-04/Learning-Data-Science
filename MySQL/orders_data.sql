SELECT * FROM ORDERS_DATA;

CREATE VIEW ORDER_DETAILS_VIEW AS SELECT * FROM ORDERS_DATA;
CREATE VIEW CUSTOMER_ORDERS AS SELECT ORDERID,CUSTOMERID,PRODUCTID,TOTALAMOUNT_INR FROM ORDERS_DATA;
CREATE VIEW ORDER_PAYMENT_VIEW AS SELECT ORDERID,CUSTOMERID,TOTALAMOUNT_INR,PAYMENTMODE FROM ORDERS_DATA;
CREATE VIEW DELIVERED_ORDERS AS SELECT * FROM ORDERS_DATA WHERE ORDERSTATUS='Delivered';
CREATE VIEW HIGH_VALUE_ORDERS AS SELECT * FROM ORDERS_DATA WHERE TOTALAMOUNT_INR>50000;

SELECT * FROM CUSTOMER_ORDERS LIMIT 5;
SELECT * FROM ORDER_DETAILS_VIEW ORDER BY ORDERDATE DESC LIMIT 10;
SELECT DISTINCT CUSTOMERID FROM CUSTOMER_ORDERS;

