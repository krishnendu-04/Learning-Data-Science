num1 = 10
num2 = 20
num3 = 30
print("Use of AND operator")
print(num1<num2 and num2<num3)
print(num1>num2 and num2<num3)
print(num1>num2 and num2>num3)

print("Use of OR operator")
print(num1<num2 or num2<num3)
print(num1>num2 or num2<num3)
print(num1>num2 or num2>num3)

print("Use of NOT operator")
print(not(num1<num2))
print(not(num1>num2))